using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Invex.StructuredText.Generators;

/// <summary>
///     Turns a <c>*.contexts</c> data file into a typed context catalogue.
///     Each line is <c>path | type | summary</c>, where type is <c>string</c>, <c>bool</c>, <c>number</c> or <c>json</c>.
///     The file name (e.g. <c>github.contexts</c>) names the root class (<c>GitHub</c>) and the root context
///     whose members appear directly on that class.
/// </summary>
[Generator]
public sealed class ContextCatalogueGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidLine = new("STG001", "Invalid context line",
        "Line {0} of {1} isn't 'path | type | summary': {2}", "Invex.StructuredText", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider.Where(static f => f.Path.EndsWith(".contexts", StringComparison.Ordinal));

        var options = context.AnalyzerConfigOptionsProvider.Select(static (o, _) =>
            o.GlobalOptions.TryGetValue("build_property.RootNamespace", out var ns) ? ns : "Generated");

        context.RegisterSourceOutput(files.Combine(options), static (spc, input) =>
        {
            var (file, ns) = input;
            var fileName = Path.GetFileName(file.Path);
            var rootContext = fileName.Substring(0, fileName.IndexOf('.'));
            var className = rootContext == "github" ? "GitHub" : Pascal(rootContext);
            var root = new Node(rootContext, rootContext);
            var lineNumber = 0;

            foreach (var line in file.GetText(spc.CancellationToken)!.Lines.Select(x => x.ToString()))
            {
                lineNumber++;
                var trimmed = line.Trim();

                if (trimmed.Length == 0 || trimmed.StartsWith("#", StringComparison.Ordinal))
                    continue;

                var parts = trimmed.Split(new[] { '|' }, 3).Select(x => x.Trim()).ToArray();

                if (parts.Length != 3 || parts[1] is not ("string" or "bool" or "number" or "json"))
                {
                    spc.ReportDiagnostic(Diagnostic.Create(InvalidLine, Location.None, lineNumber, fileName, trimmed));

                    continue;
                }

                var segments = parts[0].Split('.');

                // Members of the root context hang directly off the root class; other contexts become members of it too.
                var node = root;
                var start = segments[0] == rootContext ? 1 : 0;

                if (segments.Length == 1 && segments[0] == rootContext)
                {
                    root.Type = parts[1];
                    root.Summary = parts[2];

                    continue;
                }

                for (var i = start; i < segments.Length; i++)
                {
                    var key = segments[i];

                    if (!node.Children.TryGetValue(key, out var child))
                        node.Children[key] = child = new(key, string.Join(".", segments.Take(i + 1)));

                    node = child;
                }

                node.Type = parts[1];
                node.Summary = parts[2];
            }

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/> by Invex.StructuredText.Generators from " + fileName);
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using Invex.StructuredText.Expressions;");
            sb.AppendLine("using JetBrains.Annotations;");
            sb.AppendLine();
            sb.AppendLine($"namespace {ns};");
            sb.AppendLine();
            sb.AppendLine("/// <summary>");
            sb.AppendLine($"///     Typed references to the <c>{rootContext}</c> context and the other contexts available to expressions.");
            sb.AppendLine("/// </summary>");
            sb.AppendLine("[PublicAPI]");
            sb.AppendLine($"public static partial class {className}");
            sb.AppendLine("{");

            if (root.Type is not null)
                EmitMember(sb, "    ", "Context", root, className, isStatic: true);

            var records = new List<(string Name, Node Node)>();

            foreach (var child in root.Children.Values)
                EmitMember(sb, "    ", Pascal(child.Key), child, className, isStatic: true, records);

            sb.AppendLine("}");

            // Context records for nodes that have their own members.
            for (var i = 0; i < records.Count; i++)
            {
                var (recordName, node) = records[i];
                sb.AppendLine();
                sb.AppendLine("/// <summary>");
                sb.AppendLine($"///     The <c>{node.Path}</c> context. {node.Summary}");
                sb.AppendLine("/// </summary>");
                sb.AppendLine("[PublicAPI]");
                sb.AppendLine($"public sealed record {recordName} : JsonExpr, IContextPath");
                sb.AppendLine("{");
                sb.AppendLine("    /// <inheritdoc />");
                sb.AppendLine($"    public string Path => \"{node.Path}\";");
                sb.AppendLine();
                sb.AppendLine("    /// <inheritdoc />");
                sb.AppendLine("    public override global::System.Collections.Generic.IEnumerable<Expr> Children => [];");

                foreach (var child in node.Children.Values)
                    EmitMember(sb, "    ", Pascal(child.Key), child, recordName, isStatic: false, records);

                sb.AppendLine("}");
            }

            spc.AddSource($"{className}.Contexts.g.cs", sb.ToString());
        });
    }

    private static void EmitMember(StringBuilder sb, string indent, string name, Node node, string owner, bool isStatic,
        List<(string Name, Node Node)>? records = null)
    {
        var modifier = isStatic ? "static " : "";
        sb.AppendLine();
        sb.AppendLine($"{indent}/// <summary>");
        sb.AppendLine($"{indent}///     <c>{node.Path}</c>: {node.Summary ?? "Container for the members below."}");
        sb.AppendLine($"{indent}/// </summary>");

        if (node.Children.Count > 0 && records is not null)
        {
            var recordName = (owner.EndsWith("Context", StringComparison.Ordinal) ? owner.Substring(0, owner.Length - 7) : owner) + name + "Context";
            records.Add((recordName, node));
            sb.AppendLine($"{indent}public {modifier}{recordName} {name} {{ get; }} = new();");

            return;
        }

        var (type, ctor) = node.Type switch
        {
            "string" => ("StringExpr", "StringContext"),
            "bool" => ("BoolExpr", "BoolContext"),
            "number" => ("NumberExpr", "NumberContext"),
            _ => ("JsonExpr", "JsonContext"),
        };

        sb.AppendLine($"{indent}public {modifier}{type} {name} {{ get; }} = new {ctor}(\"{node.Path}\");");
    }

    private static string Pascal(string value) =>
        string.Concat(value
            .Split('_', '-')
            .Where(x => x.Length > 0)
            .Select(x => char.ToUpperInvariant(x[0]) + (x.All(c => !char.IsLower(c)) ? x.Substring(1).ToLowerInvariant() : x.Substring(1))));

    private sealed class Node(string key, string path)
    {
        public string Key { get; } = key;

        public string Path { get; } = path;

        public string? Type { get; set; }

        public string? Summary { get; set; }

        public Dictionary<string, Node> Children { get; } = new();
    }
}
